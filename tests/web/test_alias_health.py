"""Regression: Avahi success alone does not mean a browser can use the alias.

These tests also run with unittest when the host has no pytest installed.
"""
import sys
import tempfile
import unittest
from pathlib import Path
from types import SimpleNamespace
from unittest.mock import patch

from bc250cc.infrastructure import web_network

sys.path.insert(0, str(Path(__file__).resolve().parents[2] / 'privileged/lib'))
from system_setup_common import STATE, Host, SetupError  # noqa: E402
from system_setup_mdns import repair  # noqa: E402


class AliasHealthTests(unittest.TestCase):
    def health(self, output, published='bc250cc.local'):
        with patch.object(web_network, 'addresses', return_value=['192.168.0.8']), \
             patch.object(web_network, 'local_hostname', return_value=published), \
             patch.object(web_network.subprocess, 'run', return_value=SimpleNamespace(stdout=output)):
            return web_network.alias_health()

    def test_cachyos_avahi_success_but_nss_failure(self):
        self.assertEqual(self.health(''), {'status': 'resolver_failed', 'repairable': True})

    def test_working_resolver(self):
        self.assertEqual(self.health('192.168.0.8 STREAM bc250cc.local'), {'status': 'ready', 'repairable': False})

    def test_local_browser_loopback_alias_is_valid(self):
        self.assertEqual(self.health('127.0.0.1 STREAM bc250cc.local'),
                         {'status': 'ready', 'repairable': False})

    def test_name_collision_is_not_repaired(self):
        self.assertEqual(self.health('192.168.0.99 STREAM bc250cc.local')['status'], 'conflict')

    def test_publication_failure(self):
        self.assertEqual(self.health('', '')['status'], 'publication_failed')

    def test_timeout_is_not_a_success(self):
        with patch.object(web_network, 'addresses', return_value=[]), \
             patch.object(web_network.subprocess, 'run', side_effect=TimeoutError()):
            self.assertEqual(web_network.alias_health()['status'], 'unavailable')


class RepairTests(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory()
        self.addCleanup(self.temp.cleanup)
        self.root = Path(self.temp.name)
        self.file = self.root / 'etc/nsswitch.conf'
        self.file.parent.mkdir()
        self.original = '# local settings\npasswd: files systemd\nhosts: mymachines resolve [!UNAVAIL=return] files myhostname dns\n'
        self.file.write_text(self.original)
        library = self.root / 'usr/lib/libnss_mdns4_minimal.so.2'
        library.parent.mkdir(parents=True)
        library.touch()
        self.fail = False
        def run(*args, **kwargs):
            if args[0] == 'ip':
                return '[{"addr_info": [{"local": "192.168.0.8"}]}]'
            if args[0] == 'avahi-resolve-host-name':
                return 'bc250cc.local 192.168.0.8'
            if self.fail:
                raise SetupError('lookup failed')
            return '192.168.0.8 STREAM bc250cc.local'
        self.host = Host(self.root, run)

    def test_preserves_other_lines_and_backs_up_original(self):
        self.assertTrue(repair(self.host)['verified'])
        self.assertIn('hosts: mdns4_minimal [NOTFOUND=return] mymachines resolve', self.file.read_text())
        self.assertTrue(self.file.read_text().startswith('# local settings\npasswd: files systemd\n'))
        self.assertEqual(self.host.path(f'{STATE}/nsswitch.conf.before-mdns').read_text(), self.original)

    def test_idempotent_and_keeps_first_backup(self):
        repair(self.host)
        self.assertFalse(repair(self.host)['changed'])
        self.assertEqual(self.host.path(f'{STATE}/nsswitch.conf.before-mdns').read_text(), self.original)

    def test_failure_restores_original(self):
        self.fail = True
        with self.assertRaises(SetupError):
            repair(self.host)
        self.assertEqual(self.file.read_text(), self.original)

    def test_unsupported_missing_module_preserves_configuration(self):
        self.host.path('/usr/lib/libnss_mdns4_minimal.so.2').unlink()
        with self.assertRaisesRegex(SetupError, 'unavailable on this distribution'):
            repair(self.host)
        self.assertEqual(self.file.read_text(), self.original)

    def test_managed_configuration_preserved(self):
        self.file.write_text('# Generated by authselect\n' + self.original)
        with self.assertRaisesRegex(SetupError, 'managed'):
            repair(self.host)

    def test_existing_mdns_is_moved_before_resolve(self):
        self.file.write_text('hosts: files resolve [!UNAVAIL=return] mdns_minimal [NOTFOUND=return] dns # keep\n')
        repair(self.host)
        text = self.file.read_text()
        self.assertEqual(text.count('mdns'), 1)
        self.assertIn('resolve [!UNAVAIL=return]', text)
        self.assertIn('# keep', text)

    def test_ambiguous_configuration_preserved(self):
        self.file.write_text('hosts: files\nhosts: dns\n')
        with self.assertRaisesRegex(SetupError, 'ambiguous'):
            repair(self.host)

    def test_symlink_is_rejected(self):
        self.file.rename(self.file.with_suffix('.original'))
        self.file.symlink_to(self.file.with_suffix('.original'))
        with self.assertRaisesRegex(SetupError, 'symbolic link'):
            repair(self.host)

    def _authselect_link(self, hosts):
        """Fedora/Bazzite layout: /etc/nsswitch.conf -> /etc/authselect/nsswitch.conf."""
        target = self.root / 'etc/authselect/nsswitch.conf'
        target.parent.mkdir()
        target.write_text(f'# Generated by authselect\n# Do not modify this file manually.\n{hosts}\n')
        self.file.unlink()
        self.file.symlink_to('/etc/authselect/nsswitch.conf')
        return target

    def test_authselect_link_with_mdns_already_enabled_is_left_untouched(self):
        # Bazzite 45: authselect "with-mdns4" already put mdns4_minimal first.
        target = self._authselect_link('hosts:      files myhostname mdns4_minimal [NOTFOUND=return] resolve [!UNAVAIL=return] dns')
        before = target.read_text()
        result = repair(self.host)
        self.assertTrue(result['verified'])
        self.assertFalse(result['changed'])
        self.assertEqual(target.read_text(), before)
        self.assertTrue(self.file.is_symlink())
        self.assertFalse(self.host.path(f'{STATE}/nsswitch.conf.before-mdns').exists())

    def test_authselect_link_without_mdns_explains_the_supported_command(self):
        target = self._authselect_link('hosts:      files myhostname resolve [!UNAVAIL=return] dns')
        before = target.read_text()
        with self.assertRaisesRegex(SetupError, 'authselect enable-feature with-mdns4'):
            repair(self.host)
        self.assertEqual(target.read_text(), before)

    def test_authselect_link_with_mdns_after_the_resolver_is_not_enough(self):
        self._authselect_link('hosts: files resolve [!UNAVAIL=return] mdns4_minimal [NOTFOUND=return] dns')
        with self.assertRaisesRegex(SetupError, 'authselect'):
            repair(self.host)

    def test_other_link_targets_are_still_rejected(self):
        for destination in ('/etc/other/nsswitch.conf', '/tmp/nsswitch.conf', '../etc/passwd'):
            with self.subTest(destination=destination):
                self.file.unlink(missing_ok=True)
                self.file.symlink_to(destination)
                with self.assertRaisesRegex(SetupError, 'symbolic link'):
                    repair(self.host)

    def test_authselect_target_that_is_itself_a_link_is_rejected(self):
        target = self.root / 'etc/authselect/nsswitch.conf'
        target.parent.mkdir()
        real = self.root / 'etc/authselect/real.conf'
        real.write_text('hosts: files mdns4_minimal [NOTFOUND=return] dns\n')
        target.symlink_to(real)
        self.file.unlink()
        self.file.symlink_to('/etc/authselect/nsswitch.conf')
        with self.assertRaisesRegex(SetupError, 'symbolic link'):
            repair(self.host)

    def test_supported_package_managers_install_missing_module(self):
        for family, manager in [('arch', 'pacman'), ('debian', 'apt-get'), ('fedora', 'dnf')]:
            with self.subTest(family=family):
                library = self.host.path('/usr/lib/libnss_mdns4_minimal.so.2')
                library.unlink(missing_ok=True)
                original_runner = self.host.runner
                calls = []
                def install(*args, **kwargs):
                    calls.append(args)
                    if args[0] == manager:
                        library.touch()
                        return ''
                    return original_runner(*args, **kwargs)
                self.host.runner = install
                with patch.object(self.host, 'distro_family', return_value=family):
                    repair(self.host)
                self.assertTrue(any(call[0] == manager for call in calls))
                self.host.runner = original_runner

    def test_immutable_missing_module_does_not_run_package_manager(self):
        self.host.path('/usr/lib/libnss_mdns4_minimal.so.2').unlink()
        with patch.object(self.host, 'immutable_image', return_value=True):
            with self.assertRaisesRegex(SetupError, 'system image lacks'):
                repair(self.host)
        self.assertEqual(self.file.read_text(), self.original)

    def test_foreign_advertised_address_preserves_resolver(self):
        original_runner = self.host.runner
        def foreign(*args, **kwargs):
            if args[0] == 'avahi-resolve-host-name':
                return 'bc250cc.local 192.168.0.99'
            return original_runner(*args, **kwargs)
        self.host.runner = foreign
        with self.assertRaisesRegex(SetupError, 'another device'):
            repair(self.host)
        self.assertEqual(self.file.read_text(), self.original)

    def test_service_start_uses_detected_init(self):
        for init in ['systemd', 'openrc']:
            with self.subTest(init=init):
                systemd = self.host.path('/run/systemd/system')
                if init == 'systemd':
                    systemd.mkdir(parents=True)
                else:
                    systemd.rmdir()
                    openrc = self.host.path('/run/openrc/softlevel')
                    openrc.parent.mkdir(parents=True)
                    openrc.touch()
                original_runner = self.host.runner
                calls = []
                def stopped(*args, **kwargs):
                    calls.append(args)
                    if args[0] == 'avahi-resolve-host-name' and len(calls) == 1:
                        raise SetupError('daemon stopped')
                    if args[0] in {'systemctl', 'rc-service', 'rc-update'}:
                        return ''
                    return original_runner(*args, **kwargs)
                self.host.runner = stopped
                repair(self.host)
                self.assertTrue(any(c[0] == ('systemctl' if init == 'systemd' else 'rc-service') for c in calls))
                self.host.runner = original_runner


class PairingRegressionTests(unittest.TestCase):
    def test_unresolvable_alias_never_replaces_numeric_url(self):
        from bc250cc.infrastructure import web_control, web_devices, web_tls
        for status in ['resolver_failed', 'ready', 'conflict']:
            with self.subTest(status=status), \
                 patch.object(web_control, 'options', return_value={'port': 8250, 'tls': True, 'lan': True}), \
                 patch.object(web_control, 'addresses', return_value=['192.168.0.8']), \
                 patch.object(web_control, '_listening', return_value=True), \
                 patch.object(web_control, 'access_key', return_value='TEST'), \
                 patch.object(web_control, 'certificate_fingerprint', return_value=''), \
                 patch.object(web_control, 'autostart_state', return_value={}), \
                 patch.object(web_network, 'local_hostname', return_value='bc250cc.local'), \
                 patch.object(web_network, 'alias_health', return_value={'status': status}), \
                 patch.object(web_network, 'home_networks', return_value=[]), \
                 patch.object(web_devices, 'devices', return_value=[]), \
                 patch.object(web_tls, 'fingerprint', return_value=''):
                state = web_control.status()
                self.assertIn('https://192.168.0.8:8250', state['urls'])
                self.assertEqual('https://bc250cc.local:8250' in state['urls'], status == 'ready')

    def test_publisher_recovers_when_avahi_is_installed_later(self):
        from bc250cc.infrastructure import web_mdns
        available = []
        process = SimpleNamespace(poll=lambda: None, terminate=lambda: None, wait=lambda **kwargs: None)
        with patch.object(web_mdns.shutil, 'which', side_effect=lambda name: available[0] if available else None), \
             patch.object(web_mdns.threading, 'Thread', return_value=SimpleNamespace(start=lambda: None, join=lambda **kwargs: None)), \
             patch.object(web_mdns.web_network, 'home_networks', return_value=['192.168.0.0/24']), \
             patch.object(web_mdns, 'addresses', return_value=['192.168.0.8']), \
             patch.object(web_mdns.subprocess, 'Popen', return_value=process) as spawn:
            with web_mdns.LanAlias(True) as alias:
                spawn.assert_not_called()
                available.append('/usr/bin/avahi-publish-address')
                alias._refresh()
                self.assertEqual(spawn.call_args.args[0][-2:], ['bc250cc.local', '192.168.0.8'])


class SteamOSPublicationRepairTests(unittest.TestCase):
    def setUp(self):
        RepairTests.setUp(self)
        self.host.path('/etc/os-release').write_text('ID=steamos\nID_LIKE=arch\n')
        self.host.path('/run/systemd/system').mkdir(parents=True)
        self.config = self.host.path('/etc/avahi/avahi-daemon.conf')
        self.config.parent.mkdir(parents=True)
        self.avahi_original = ('# keep my settings\n[server]\nuse-ipv6=yes\n'
                               '[publish]\ndisable-publishing=yes\n'
                               'disable-user-service-publishing=yes\npublish-addresses=no\n')
        self.config.write_text(self.avahi_original)
        self.calls = []
        original_runner = self.host.runner
        def run(*args, **kwargs):
            self.calls.append(args)
            if args[0] == 'systemctl':
                return ''
            return original_runner(*args, **kwargs)
        self.host.runner = run

    def test_enables_only_publication_flags_and_keeps_steamos_update_files(self):
        result = repair(self.host)
        self.assertTrue(result['verified'])
        updated = self.config.read_text()
        self.assertIn('disable-publishing=no', updated)
        self.assertIn('disable-user-service-publishing=no', updated)
        self.assertIn('publish-addresses=no', updated)
        self.assertIn('use-ipv6=yes', updated)
        self.assertEqual(self.host.path(result['publication_backup']).read_text(), self.avahi_original)
        self.assertIn(('systemctl', 'restart', 'avahi-daemon.service'), self.calls)
        keep = self.host.read('/etc/atomic-update.conf.d/bc250-control-center-mdns.conf')
        self.assertIn('/etc/avahi/avahi-daemon.conf', keep)
        self.assertIn('/etc/nsswitch.conf', keep)

    def test_resolver_failure_restores_avahi_and_nss(self):
        self.fail = True
        with self.assertRaises(SetupError):
            repair(self.host)
        self.assertEqual(self.config.read_text(), self.avahi_original)
        self.assertEqual(self.file.read_text(), self.original)
        self.assertFalse(self.host.path('/etc/atomic-update.conf.d/bc250-control-center-mdns.conf').exists())
        self.assertEqual(self.calls.count(('systemctl', 'restart', 'avahi-daemon.service')), 2)

    def test_duplicate_publication_keys_are_preserved(self):
        self.config.write_text(self.avahi_original + 'disable-publishing=no\n')
        with self.assertRaisesRegex(SetupError, 'ambiguous or invalid'):
            repair(self.host)
        self.assertTrue(self.config.read_text().endswith('disable-publishing=no\n'))
        self.assertEqual(self.calls, [])

    def test_publication_config_symlink_is_rejected(self):
        target = self.config.with_suffix('.original')
        self.config.rename(target)
        self.config.symlink_to(target)
        with self.assertRaisesRegex(SetupError, 'symbolic link'):
            repair(self.host)
        self.assertEqual(target.read_text(), self.avahi_original)


    def test_repeated_repair_keeps_the_first_publication_backup(self):
        result = repair(self.host)
        restart_count = self.calls.count(('systemctl', 'restart', 'avahi-daemon.service'))
        self.assertFalse(repair(self.host)['changed'])
        self.assertEqual(self.host.path(result['publication_backup']).read_text(), self.avahi_original)
        self.assertEqual(self.calls.count(('systemctl', 'restart', 'avahi-daemon.service')), restart_count)

    def test_name_collision_restores_publication_configuration(self):
        runner = self.host.runner
        def foreign(*args, **kwargs):
            if args[0] == 'getent':
                return '192.168.0.8 STREAM bc250cc.local\n192.168.0.99 STREAM bc250cc.local'
            return runner(*args, **kwargs)
        self.host.runner = foreign
        with self.assertRaisesRegex(SetupError, 'still does not resolve'):
            repair(self.host)
        self.assertEqual(self.config.read_text(), self.avahi_original)
        self.assertEqual(self.file.read_text(), self.original)



    def test_flatpak_local_alias_preserves_hosts_and_verifies_loopback(self):
        hosts = self.host.path('/etc/hosts')
        original = '127.0.0.1 localhost\n192.168.0.44 printer # keep\n'
        hosts.write_text(original)
        runner = self.host.runner
        def loopback(*args, **kwargs):
            if args[0] == 'getent':
                return '127.0.0.1 STREAM bc250cc.local'
            return runner(*args, **kwargs)
        self.host.runner = loopback
        result = repair(self.host)
        self.assertTrue(result['verified'])
        self.assertEqual(hosts.read_text().count('bc250cc.local'), 1)
        self.assertTrue(hosts.read_text().startswith(original))
        self.assertEqual(self.host.path(result['hosts_backup']).read_text(), original)
        self.assertIn('/etc/hosts', self.host.read('/etc/atomic-update.conf.d/bc250-control-center-web-host.conf'))
        self.assertFalse(repair(self.host)['changed'])

    def test_hosts_is_restored_if_verification_fails(self):
        hosts = self.host.path('/etc/hosts')
        original = '127.0.0.1 localhost\n'
        hosts.write_text(original)
        self.fail = True
        with self.assertRaises(SetupError):
            repair(self.host)
        self.assertEqual(hosts.read_text(), original)
        self.assertEqual(self.config.read_text(), self.avahi_original)
        self.assertFalse(self.host.path('/etc/atomic-update.conf.d/bc250-control-center-web-host.conf').exists())

    def test_foreign_hosts_alias_is_never_replaced(self):
        hosts = self.host.path('/etc/hosts')
        original = '192.168.0.99 bc250cc.local\n'
        hosts.write_text(original)
        with self.assertRaisesRegex(SetupError, 'existing hosts entry'):
            repair(self.host)
        self.assertEqual(hosts.read_text(), original)
        self.assertEqual(self.config.read_text(), self.avahi_original)



class AliasTimeoutRepairTests(unittest.TestCase):
    def test_timeout_keeps_explicit_repair_available_on_a_connected_host(self):
        import subprocess
        with patch.object(web_network, 'addresses', return_value=['192.168.0.8']), \
             patch.object(web_network.subprocess, 'run', side_effect=subprocess.TimeoutExpired('getent', 3)):
            self.assertEqual(web_network.alias_health(), {'status': 'unavailable', 'repairable': True})
