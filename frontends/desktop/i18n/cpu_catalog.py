"""Exact translations for the CPU / SMU module.

The CPU page mixes safety dialogs, live state labels and app-generated console
messages.  Keeping those strings in one catalog makes the module auditable and
prevents a new feature from silently falling back to English in one language.
Hardware identifiers, file paths and upstream command output are intentionally
left untouched.
"""
from __future__ import annotations

from .catalog import EXTRA_TRANSLATIONS
from .interface_catalog import INTERFACE_TRANSLATIONS


def _cpu(en: str, es: str, pt: str, ru: str, uk: str, de: str, pl: str):
    return en, {
        "en": en,
        "es": es,
        "pt": pt,
        "ru": ru,
        "uk": uk,
        "de": de,
        "pl": pl,
    }


def _pl_only(en: str, pl: str):
    """Reuse the already-reviewed 5-language mapping and add Polish exactly."""
    base = INTERFACE_TRANSLATIONS.get(en) or EXTRA_TRANSLATIONS.get(en)
    if not base:
        raise KeyError(f"CPU Polish supplement has no base translation: {en}")
    mapping = dict(base)
    mapping["pl"] = pl
    return en, mapping


