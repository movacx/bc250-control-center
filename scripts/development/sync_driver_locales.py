def main() -> None:
    missing = sorted({path.stem for path in ROOT.glob("*.json")} - set(T))
    if missing:
        raise SystemExit("Add reviewed translations for: " + ", ".join(missing))
    for locale, values in T.items():
        if len(values) != len(SOURCES):
            raise SystemExit(
                f"{locale}: expected {len(SOURCES)} values, got {len(values)}"
            )
        path = ROOT / f"{locale}.json"
        catalog = json.loads(path.read_text(encoding="utf-8"))
        catalog.update(dict(zip(SOURCES, values, strict=True)))
        catalog.update(
            dict(zip(("Loading", "Wi-Fi", "Distribution"), EXTRA[locale], strict=True))
        )
        path.write_text(
            json.dumps(catalog, ensure_ascii=False, indent=2, sort_keys=True) + "\n",
            encoding="utf-8",
        )


